import json
from datetime import datetime, timedelta
from google.adk.agents.llm_agent import Agent


def make_ics(events: list[dict]) -> str:
    """Creates a calendar file (plan.ics) with study blocks for Google Calendar."""
    if isinstance(events, str):
        events = json.loads(events)

    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//SyllabusPilot//Study Plan//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
    ]

    for ev in events:
        title = ev.get("title", "Study Session")
        date_str = ev.get("date", "2026-11-10")
        time_str = ev.get("start_time", "18:00")
        duration = float(ev.get("duration_hours", 2.0))
        desc = ev.get("description", "Study session generated by SyllabusPilot")

        start_dt = datetime.strptime(f"{date_str} {time_str}", "%Y-%m-%d %H:%M")
        end_dt = start_dt + timedelta(hours=duration)

        lines.extend([
            "BEGIN:VEVENT",
            f"SUMMARY:{title}",
            f"DESCRIPTION:{desc}",
            f"DTSTART:{start_dt.strftime('%Y%m%dT%H%M00')}",
            f"DTEND:{end_dt.strftime('%Y%m%dT%H%M00')}",
            f"UID:{datetime.now().timestamp()}-{title.replace(' ', '')}@syllabuspilot",
            "STATUS:CONFIRMED",
            "END:VEVENT",
        ])

    lines.append("END:VCALENDAR\n")

    with open("plan.ics", "w", encoding="utf-8") as f:
        f.write("\r\n".join(lines))

    return f"Successfully saved {len(events)} study sessions to plan.ics! You can now import this into Google Calendar."


root_agent = Agent(
    model="gemini-3.8-flash",
    name="syllabus_pilot",
    description="An academic agent that extracts deadlines and builds balanced study schedules.",
    instruction="""You are SyllabusPilot, an expert academic planner assistant.
Your job is to transform any messy syllabus (PDF, text, or image) into an actionable study plan.

Follow this exact process:
1. Scan the syllabus and find EVERY graded item (assignments, quizzes, labs, papers, exams).
2. Display a Markdown table of all graded items with columns: | Graded Item | Due Date | Weight (%) |.
3. Ask at most 1 to 3 quick questions to personalize the plan (such as: how many hours a week can you study, and what time of day do you prefer?).
4. When the user responds with their study availability:
   - Create a balanced week-by-week study plan leading up to the deadlines.
   - Allocate more prep hours for high-weight tests and essays.
   - Call the `make_ics` tool to generate `plan.ics` with specific dates, times, and study tasks.
   - Show a concise week-by-week summary in the chat and let the user know their `plan.ics` is ready to import into Google Calendar.
""",
    tools=[make_ics],
)
